# -*- coding: utf-8 -*-
"""
Лабораторная работа №2. Задание 1.
Вариант 3: поиск корректных URI адресов в тексте.

Поддерживаемые протоколы:
    http, https (RFC 7230)
    ftp        (RFC 3986)
    sftp, ssh, smb (draft)

Стандарт URI: RFC 3986
"""

import re

# ============================================================
# РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ ДЛЯ ПОИСКА КОРРЕКТНЫХ URI
# ============================================================
URI_REGEX = re.compile(r"""
    # ============================================================
    # ЛЕВАЯ ГРАНИЦА
    # Совпадение разрешено, только если слева НЕТ буквы/цифры.
    # Отсекает ложные срабатывания: "hhttp://", "abcftp://".
    # ============================================================
    (?<![A-Za-z0-9])

    # ============================================================
    # СХЕМА (ПРОТОКОЛ)
    # Независимая группа: http, https, ftp, sftp, ssh, smb.
    # После схемы — обязательный разделитель "://".
    # ============================================================
    (?:
        https?  |  ftp  |  sftp  |  ssh  |  smb
    )
    ://

    # ============================================================
    # USERINFO (НЕОБЯЗАТЕЛЬНО)
    # Формат: login[:password]@ перед хостом (RFC 3986 §3.2.1).
    # Внутри: разрешённые символы userinfo ИЛИ percent-encoded октет
    # (%XX). "+" — один и более; "@" — разделитель с хостом.
    # Внешняя (?:...)? делает всю часть необязательной.
    # Пример: ssh://login@server.com
    # ============================================================
    (?:
        (?:[A-Za-z0-9\-._~!$&'()*+,;=:]|%[0-9A-Fa-f]{2})+@
    )?

    # ============================================================
    # ХОСТ (одна из трёх альтернатив)
    # ============================================================
    (?:

        # --------------------------------------------------------
        # Вариант A: IPv4-адрес.
        # Четыре группы по 1–3 цифры через точку: N.N.N.N.
        # ВНИМАНИЕ: не проверяет диапазон 0–255.
        # Пример: 127.0.0.1
        # --------------------------------------------------------
        # (?:\d{1,3}\.){3}\d{1,3}
        1?[0-9]?[0-9] | (25[0-5]|2?[0-4]?[0-9])
        |

        # --------------------------------------------------------
        # Вариант B: IPv6-адрес в квадратных скобках.
        # "\[" и "\]" экранированы — это литералы, не символьный класс.
        # Внутри: hex-цифры, двоеточия, точки.
        # Пример: [::1], [2001:db8::1]
        # --------------------------------------------------------
        \[[0-9A-Fa-f:.]+\]
        |

        # --------------------------------------------------------
        # Вариант C: доменное имя.
        # Метка DNS: [A-Za-z0-9] (?:[A-Za-z0-9\-]* [A-Za-z0-9])?
        #   — не начинается и не заканчивается дефисом (RFC 1035).
        # "(?:метка\.)+" — одна или более меток с точкой,
        # затем одна метка БЕЗ точки в конце (TLD).
        # Пример: example.com, xn--fsqu00a.xn--3lr804guic
        # --------------------------------------------------------
        (?:
            (?:[A-Za-z0-9](?:[A-Za-z0-9\-]*[A-Za-z0-9])?\.)+
            [A-Za-z0-9](?:[A-Za-z0-9\-]*[A-Za-z0-9])?
        )
    )

    # ============================================================
    # ПОРТ (НЕОБЯЗАТЕЛЬНО)
    # ":" + 1–5 цифр.
    # ВНИМАНИЕ: не проверяет диапазон 0–65535.
    # Пример: :1235, :8080
    # ============================================================
    (?::\d{1,5})?

    # ============================================================
    # ПУТЬ / QUERY / FRAGMENT (НЕОБЯЗАТЕЛЬНО)
    # "[/?#]" — первый символ части (обязателен, если часть есть).
    # "[...]*" — дальнейшие разрешённые символы (ноль или более).
    # "#" экранирован "\#", иначе в re.VERBOSE начнёт комментарий.
    # Пример: /articles/page1?v=2&s=ex
    # ============================================================
    (?:[/?#][A-Za-z0-9\-._~!$&'()*+,;=:@%/?\#]*)?

    # ============================================================
    # ПРАВАЯ ГРАНИЦА
    # Совпадение разрешено, только если справа НЕТ ни одного
    # символа из набора URI. Гарантирует, что URI закончился,
    # а не «прилип» к следующему куску текста.
    # Пример: "http://example.comfoo" не даст совпадения вообще.
    # ============================================================
    (?![A-Za-z0-9\-._~!$&'()*+,;=:@%/?])
""", re.VERBOSE)


def find_uris(text: str) -> list[str]:
    """Находит все корректные URI в тексте."""
    return [m.group(0) for m in URI_REGEX.finditer(text)]


def highlight_uris(text: str, color: str = "\033[42m\033[30m") -> str:
    """Подсвечивает найденные URI зелёным фоном."""
    RESET = "\033[0m"
    result, last_end = [], 0
    for match in URI_REGEX.finditer(text):
        start, end = match.span()
        result.append(text[last_end:start])
        result.append(color + text[start:end] + RESET)
        last_end = end
    result.append(text[last_end:])
    return "".join(result)


