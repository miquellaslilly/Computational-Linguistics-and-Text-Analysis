import re

date_mention_pattern = re.compile(r'''
    (?:
        # --- Предлог ---
        (?:(?:в|во|с|со|по|до|от|на|к|ко|о|об|за|под|над|при|для|через|около|после|перед|между)\s+)?
        (?:
            # --- Вариант 1: [день недели] + число + месяц + [год] ---
            (?:
                (?:(?:понедельник|вторник|среду?|четверг|пятницу?|субботу?|воскресенье)\s*,?\s*)?
                \d{1,2}\s+
                (?:января|февраля|марта|апреля|мая|июня|
                   июля|августа|сентября|октября|ноября|декабря)
                (?:\s+\d{4})?
                (?:\s+(?:года|году|годов|годы|год|г\.?))?
            )
            |
            # --- Вариант 2: Месяц + число + год (английский) ---
            (?:
                (?:January|February|March|April|May|June|
                   July|August|September|October|November|December)
                \s+\d{1,2}(?:st|nd|rd|th)?,?\s*\d{4}
            )
            |
            # --- Вариант 3: диапазон "с XXXX по XXXX годы" ---
            (?:
                \d{4}\s*
                (?:-|—|–|по)\s*
                \d{4}\s*
                (?:годы|годов|г\.?)
            )
            |
            # --- Вариант 4: период "с XXXX [года] по [месяц] XXXX [год]" ---
            (?:
                \d{4}\s*(?:года|году|год|г\.?)?\s+
                по\s+
                (?:\d{1,2}\s+)?
                (?:
                    (?:января|февраля|марта|апреля|мая|июня|
                       июля|августа|сентября|октября|ноября|декабря)
                    |
                    (?:январь|февраль|март|апрель|май|июнь|
                       июль|август|сентябрь|октябрь|ноябрь|декабрь)
                )?
                \s*\d{4}\s*(?:года|году|год|г\.?)?
            )
            |
            # --- Вариант 5: только год с обязательным словом "год/года/году" ---
            # (идёт ПОСЛЕ диапазонов, чтобы не съесть их раньше)
            (?:
                \d{4}\s+(?:годов|годы|года|году|год|г\.)
            )
            |
            # --- Вариант 6: относительные даты ---
            (?:
                (?:вчера|сегодня|завтра|послезавтра|позавчера|
                   этим\s+утром|этим\s+вечером|этой\s+ночью|
                   прошлой\s+неделе|этой\s+неделе|следующей\s+неделе|
                   прошлом\s+месяце|этом\s+месяце|следующем\s+месяце|
                   прошлом\s+году|этом\s+году|следующем\s+году)
            )
        )
    )
''', re.VERBOSE | re.IGNORECASE)


def highlight_dates(text):
    GREEN = '\033[42m\033[30m'
    RESET = '\033[0m'
    result = []
    last_end = 0
    for match in date_mention_pattern.finditer(text):
        start, end = match.span()
        result.append(text[last_end:start])
        result.append(GREEN + text[start:end] + RESET)
        last_end = end
    result.append(text[last_end:])
    return ''.join(result)


text = """
Нобелевская премия в 2017 году была получена Ивановым И. И.
С августа 2019 года по декабрь 2021 года необходимо набрать…
Суммарно с 2020 года по первое полугодие 2021 года было обнаружено…
Этим утром его друзья отправились на рыбалку.
В четверг, 14 июня 2021 года состоялся концерт известной группы.
Пять недель назад 7 августа был зафиксирован новый мировой рекорд.
Великий макаронный монстр являлся правителем государства с 2013 по 2020 годы.
"""

print("=== Исходный текст ===")
print(text)
print("\n=== Текст с подсветкой ===")
print(highlight_dates(text))
print("\n=== Найденные упоминания ===")
for m in date_mention_pattern.finditer(text):
    print(f"  '{m.group().strip()}'")