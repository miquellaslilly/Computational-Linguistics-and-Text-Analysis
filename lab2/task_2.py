# -*- coding: utf-8 -*-
"""
Лабораторная работа №2. Задание 2.
Поиск в тексте упоминаний датированных событий.

Учитываются:
    - предлоги перед датой (в, с, по, на, до, ...)
    - все составные части: день недели, число, месяц, год
    - числовые форматы дд.мм.гггг / дд/мм/гггг / дд-мм-гггг
    - текстовые даты (русские и английские)
    - диапазоны дат ("с 2013 по 2020 годы")
    - относительные даты ("вчера", "пять недель назад")
"""

import re

# ============================================================
# ВСПОМОГАТЕЛЬНЫЕ ФРАГМЕНТЫ
# ============================================================
MONTHS_RUS_GEN = (
    r"(?:января|февраля|марта|апреля|мая|июня|"
    r"июля|августа|сентября|октября|ноября|декабря)"
)
MONTHS_RUS_NOM = (
    r"(?:январь|февраль|март|апрель|май|июнь|"
    r"июль|август|сентябрь|октябрь|ноябрь|декабрь)"
)
MONTHS_ENG = (
    r"(?:January|February|March|April|May|June|July|August|"
    r"September|October|November|December|"
    r"Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Oct|Nov|Dec)"
)
WEEKDAYS = (
    r"(?:понедельник|вторник|сред[ау]?|четверг|пятниц[ау]?|"
    r"суббот[ау]?|воскресень[ея])"
)
NUM_WORDS = (
    r"(?:один|одна|одно|два|две|три|четыре|пять|шесть|семь|"
    r"восемь|девять|десять|одиннадцать|двенадцать)"
)
DAY = r"\d{1,2}(?:-?(?:го|е|ое|ый|ой))?"
YEAR = r"\d{4}"


# ============================================================
# ОСНОВНОЕ РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ ДЛЯ ПОИСКА ДАТ
# ============================================================
date_mention_pattern = re.compile(rf"""
    (?<![A-Za-zА-Яа-я0-9])
    (?:
        # --- Предлог (необязательно) ---
        (?:(?:в|во|с|со|по|до|от|на|к|ко|о|об|за|под|над|при|для|
             через|около|после|перед|между)\s+)?
        (?:
            # ================================================
            # ВАРИАНТ 1: [день недели,] число + месяц(рус) + [год]
            # ================================================
            (?:
                (?:{WEEKDAYS}\s*,?\s*)?
                {DAY}\s+
                {MONTHS_RUS_GEN}
                (?:\s+{YEAR})?
                (?:\s+(?:года|году|годов|годы|год|г\.?))?
            )
            |
            # ================================================
            # ВАРИАНТ 2: Месяц(англ) + день + [,] год
            # ================================================
            (?:
                {MONTHS_ENG}
                \s+{DAY},?\s*{YEAR}
            )
            |
            # ================================================
            # ВАРИАНТ 3: год + [,] Месяц(англ) + день
            # ================================================
            (?:
                {YEAR},?\s+
                {MONTHS_ENG}
                \s+{DAY}
            )
            |
            # ================================================
            # ВАРИАНТ 4: числовая дата дд.мм.гггг / дд/мм/гггг / дд-мм-гггг
            # ================================================
            (?:
                {DAY}[./-]\d{{1,2}}[./-]{YEAR}
            )
            |
            # ================================================
            # ВАРИАНТ 5: диапазон "с XXXX по XXXX годы"
            # ================================================
            (?:
                {YEAR}\s*(?:-|—|–|по)\s*{YEAR}\s*
                (?:годы|годов|г\.?)
            )
            |
            # ================================================
            # ВАРИАНТ 6: период "с XXXX [года] по [месяц] XXXX"
            # ================================================
            (?:
                {YEAR}\s*(?:года|году|год|г\.?)?
                \s+по\s+
                (?:\d{{1,2}}\s+)?
                (?:{MONTHS_RUS_GEN}|{MONTHS_RUS_NOM})?
                \s*{YEAR}\s*(?:года|году|год|г\.?)?
            )
            |
            # ================================================
            # ВАРИАНТ 7: только год с обязательным "год/года/году/годы/г."
            # ================================================
            (?:
                {YEAR}\s+(?:годов|годы|года|году|год|г\.)
            )
            |
            # ================================================
            # ВАРИАНТ 8: относительные даты (простые)
            # ================================================
            (?:
                (?:вчера|сегодня|завтра|послезавтра|позавчера|
                   этим\s+утром|этим\s+вечером|этой\s+ночью|
                   прошлой\s+неделе|этой\s+неделе|следующей\s+неделе|
                   прошлом\s+месяце|этом\s+месяце|следующем\s+месяце|
                   прошлом\s+году|этом\s+году|следующем\s+году)
            )
            |
            # ================================================
            # ВАРИАНТ 9: относительные с числом: "пять недель назад"
            # ================================================
            (?:
                {NUM_WORDS}\s+
                (?:недель|недели|неделю|дней|дня|день|
                   месяцев|месяца|месяц|лет|года|год)
                \s+назад
            )
        )
    )
    (?![A-Za-zА-Яа-я0-9])
""", re.VERBOSE | re.IGNORECASE)


# ============================================================
# ФУНКЦИИ
# ============================================================
def find_dates(text: str) -> list[str]:
    """Находит все упоминания датированных событий в тексте."""
    return [m.group(0).strip() for m in date_mention_pattern.finditer(text)]


def highlight_dates(text: str, color: str = "\033[42m\033[30m") -> str:
    """Подсвечивает найденные даты зелёным фоном."""
    RESET = "\033[0m"
    result, last_end = [], 0
    for match in date_mention_pattern.finditer(text):
        start, end = match.span()
        result.append(text[last_end:start])
        result.append(color + text[start:end] + RESET)
        last_end = end
    result.append(text[last_end:])
    return "".join(result)


