import re

# Регулярное выражение для поиска дат в различных форматах
date_pattern = re.compile(r'''
    (?<!\d)
    (?:
        # день.месяц.год
        (?:\d{1,2}\.\d{1,2}\.\d{4})
        |
        # день/месяц/год
        (?:\d{1,2}/\d{1,2}/\d{4})
        |
        # день-месяц-год
        (?:\d{1,2}-\d{1,2}-\d{4})
        |
        # год.месяц.день
        (?:\d{4}\.\d{1,2}\.\d{1,2})
        |
        # год/месяц/день
        (?:\d{4}/\d{1,2}/\d{1,2})
        |
        # год-месяц-день
        (?:\d{4}-\d{1,2}-\d{1,2})
    )
    (?!\d)
''', re.VERBOSE)

# Тестовый текст
text = """
Корректные даты:
14.09.2023, 5.02.1995, 01.4.2012
14/09/2023, 5/02/1995, 01/4/2012
14-09-2023, 5-02-1995, 01-4-2012
2023.09.14, 1995.02.5, 2012.4.01
2023/09/14, 1995/02/5, 2012/4/01
2023-09-14, 1995-02-5, 2012-4-01
20 января 1806
1924, July 25
26/09/1635
3.1.1506

Некорректные даты:
25.08-1002
декабря 19, 1838
8.20.1973
Jun 7, -1563
"""

print("=== Исходный текст ===")
print(text)

print("\n=== Найденные даты ===")
matches = date_pattern.findall(text)
for match in matches:
    print(f"  {match}")